/**
 * One-time: MotelyItemType int → packed atlas cell.
 * Runtime is Map.get(type). Matching names to sprites happens here, not on paint.
 *
 * Run: node scripts/emit-motely-sprite-lut.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { MotelyItemType } from "motely-wasm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spriteSrc = readFileSync(join(root, "src/sprites/spriteData.ts"), "utf8");

/** 0=Jokers 1=Tarots 2=Decks */
const SHEETS = {
  JOKERS: 0,
  JOKER_FACES: 0,
  TAROTS_AND_PLANETS: 1,
  CONSUMABLE_FACES: 1,
};

function alnum(s) {
  return s.toLowerCase().replace(/[^a-z0-9]/g, "");
}

const ALIASES = new Map([
  ["eightball", "8ball"],
  ["oopsall6s", "oopsall6s"],
]);

function parseBlock(name) {
  const start = spriteSrc.indexOf(`export const ${name}`);
  if (start < 0) throw new Error(`missing ${name}`);
  const open = spriteSrc.indexOf("[", start);
  const close = spriteSrc.indexOf("];", open);
  const body = spriteSrc.slice(open, close);
  const out = [];
  const re = /\{\s*name:\s*"([^"]+)"\s*,\s*pos:\s*\{\s*x:\s*(\d+)\s*,\s*y:\s*(\d+)/g;
  let m;
  while ((m = re.exec(body))) {
    out.push({ name: m[1], x: Number(m[2]), y: Number(m[3]) });
  }
  return out;
}

const byAlnum = new Map();
for (const [block, sheet] of Object.entries(SHEETS)) {
  for (const entry of parseBlock(block)) {
    const key = alnum(entry.name);
    if (!byAlnum.has(key)) byAlnum.set(key, { sheet, x: entry.x, y: entry.y, name: entry.name });
  }
}

function pack(sheet, x, y) {
  return sheet | (x << 8) | (y << 16);
}

const RANK_COL = {
  Two: 0,
  Three: 1,
  Four: 2,
  Five: 3,
  Six: 4,
  Seven: 5,
  Eight: 6,
  Nine: 7,
  Ten: 8,
  Jack: 9,
  Queen: 10,
  King: 11,
  Ace: 12,
};
const SUIT_ROW = { Hearts: 0, Clubs: 1, Diamonds: 2, Spades: 3 };

const pairs = [];
const missing = [];
for (const name of Object.keys(MotelyItemType).filter((k) => Number.isNaN(Number(k)))) {
  const type = MotelyItemType[name];
  const of = /^(Two|Three|Four|Five|Six|Seven|Eight|Nine|Ten|Jack|Queen|King|Ace)Of(Clubs|Diamonds|Hearts|Spades)$/.exec(
    name,
  );
  if (of) {
    pairs.push([type, pack(2, RANK_COL[of[1]], SUIT_ROW[of[2]])]);
    continue;
  }
  const hit = byAlnum.get(alnum(name)) ?? byAlnum.get(ALIASES.get(alnum(name)) ?? "");
  if (!hit) {
    missing.push(`${name}=${type}`);
    continue;
  }
  pairs.push([type, pack(hit.sheet, hit.x, hit.y)]);
}

pairs.sort((a, b) => a[0] - b[0]);

const lines = [
  "/* generated by scripts/emit-motely-sprite-lut.mjs — do not edit */",
  "/** packed cell: sheet:8 | x:8 | y:8. sheet 0=Jokers 1=Tarots 2=Decks */",
  "export const MOTELY_SPRITE_BY_TYPE: ReadonlyMap<number, number> = new Map([",
  ...pairs.map(([t, p]) => `  [${t}, ${p}],`),
  "]);",
  "",
];

const outPath = join(root, "src/decode/motelySpriteLut.generated.ts");
writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${pairs.length} cells → ${outPath}`);
if (missing.length) {
  console.log(`unmapped MotelyItemType (${missing.length}): ${missing.join(", ")}`);
}
