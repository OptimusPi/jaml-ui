// Generates src/lib/jaml/engineGrammar.generated.ts from MotelyJAML's YAML loader source:
// the clause-key table in Filters/JamlConfigLoader.cs (JamlClauseConverter.Keys) and the
// public settable properties of each clause class and its sources config. The loader reads
// camelCase, case-insensitive, and rejects unmapped members, so these lists are the full
// grammar it accepts. Item names come from motely-wasm's own enums at runtime (src/engineVocab.ts).
//
// Usage: node scripts/gen-engine-grammar.mjs [path-to-MotelyJAML/Motely]
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2] ?? "D:/MotelyJAML/Motely";
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    if (name === "bin" || name === "obj") continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (p.endsWith(".cs")) files.push(p);
  }
})(root);
const sources = files.map((f) => readFileSync(f, "utf8"));

/** class name -> { base, props } for every class declared in the engine source. */
const classes = new Map();
for (const src of sources) {
  const re = /\b(?:class|record|struct)\s+(\w+)(?:\s*:\s*([\w<>, ]+))?\s*\{/g;
  let m;
  while ((m = re.exec(src))) {
    let depth = 1;
    let i = re.lastIndex;
    for (; i < src.length && depth > 0; i++) {
      if (src[i] === "{") depth++;
      else if (src[i] === "}") depth--;
    }
    const body = src.slice(re.lastIndex, i);
    // Only the class's own top-level members: drop nested braces' contents.
    let top = "";
    let d = 0;
    for (const ch of body) {
      if (ch === "{") d++;
      if (d === 0) top += ch;
      if (ch === "}") d--;
      if (d === 0 && ch === "}") top += "{}";
    }
    const props = [];
    const typeOf = {};
    const pr = /public\s+(?!static|abstract|override|const)([\w\[\]<>?,. ]+?)\s+(\w+)\s*\{\}/g;
    let p;
    while ((p = pr.exec(top))) {
      const name = p[2][0].toLowerCase() + p[2].slice(1);
      props.push(name);
      typeOf[name] = p[1].replace(/\?$/, "").trim();
    }
    const base = m[2]?.split(",")[0].trim();
    if (!classes.has(m[1])) classes.set(m[1], { base, props, typeOf });
  }
}

function allProps(name) {
  const c = classes.get(name);
  if (!c) throw new Error(`gen-engine-grammar: class ${name} not found under ${root}`);
  const inherited = c.base && classes.has(c.base) ? allProps(c.base) : { props: [], typeOf: {} };
  return { props: [...new Set([...inherited.props, ...c.props])], typeOf: { ...inherited.typeOf, ...c.typeOf } };
}

const loader = readFileSync(join(root, "Filters/JamlConfigLoader.cs"), "utf8");
const keyRe = /\["(\w+)"\]\s*=\s*new\(Ctx\.(\w+),\s*(?:"(\w+)"|null),\s*(true|false)\)/g;
const discriminators = {};
let k;
while ((k = keyRe.exec(loader))) {
  discriminators[k[1]] = { clause: k[2], valueProperty: k[3] ?? null, valueIsList: k[4] === "true" };
}
if (Object.keys(discriminators).length === 0) throw new Error("gen-engine-grammar: no clause keys parsed from JamlConfigLoader.cs");

const clauseKeys = {};
const sourceKeys = {};
for (const { clause } of Object.values(discriminators)) {
  if (clauseKeys[clause]) continue;
  const { props, typeOf } = allProps(clause);
  clauseKeys[clause] = props;
  for (const sk of ["sources", "legendarySources"]) {
    if (typeOf[sk] && classes.has(typeOf[sk])) sourceKeys[`${clause}.${sk}`] = allProps(typeOf[sk]).props;
  }
}

const rootKeys = allProps("JamlConfig").props;

// motely-wasm exports every item enum the loader reads except MotelyJokerSticker.
const stickerSrc = readFileSync(join(root, "Enums/MotelyJokerSticker.cs"), "utf8");
const stickers = [...stickerSrc.matchAll(/^\s*(\w+)\s*=\s*\d+,?/gm)].map((s) => s[1]);
if (stickers.length === 0) throw new Error("gen-engine-grammar: no values parsed from Enums/MotelyJokerSticker.cs");

const out = `// GENERATED by scripts/gen-engine-grammar.mjs from MotelyJAML/Motely (Filters/JamlConfigLoader.cs
// JamlClauseConverter.Keys + clause class properties). Do not edit; regenerate.
// scripts/check-vocab-drift.mjs runs every key here through the engine's JamlConfigLoader.check.

/** Top-level document keys (JamlConfig properties). */
export const ROOT_KEYS: readonly string[] = ${JSON.stringify(rootKeys)};

/** Clause key (the YAML mapping key, e.g. \`legendaryJoker\`) -> the clause class it loads. */
export const DISCRIMINATORS = ${JSON.stringify(discriminators, null, 2)} as const;

/** Clause class -> every key the loader maps on it (camelCase; unknown keys are rejected). */
export const CLAUSE_KEYS: Record<string, readonly string[]> = ${JSON.stringify(clauseKeys, null, 2)};

/** "<ClauseClass>.<sources key>" -> every key the loader maps inside that sources block. */
export const SOURCE_KEYS: Record<string, readonly string[]> = ${JSON.stringify(sourceKeys, null, 2)};

/** Enums/MotelyJokerSticker.cs — the one item enum motely-wasm does not export. */
export const MOTELY_JOKER_STICKER: readonly string[] = ${JSON.stringify(stickers)};
`;
writeFileSync(new URL("../src/lib/jaml/engineGrammar.generated.ts", import.meta.url), out);
console.log(`engine grammar: ${Object.keys(discriminators).length} clause keys, ${Object.keys(clauseKeys).length} clause classes, ${Object.keys(sourceKeys).length} sources blocks`);
