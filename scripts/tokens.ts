/**
 * Generates src/styles/tokens.css and src/styles/tailwind.css from src/tokens.ts.
 * Run: pnpm tokens          (writes)
 *      pnpm tokens --check  (fails if the CSS is stale; used in CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { palette, tones, themes, space, radius, font, fontSize, motion, depth, size } from '../src/tokens.ts';

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const v = (name: string) => `--j-${kebab(name)}`;
const header = '/* GENERATED by scripts/tokens.ts from src/tokens.ts. Do not edit by hand. */\n';

const lines = (entries: [string, string][], indent = '  ') =>
  entries.map(([k, val]) => `${indent}${k}: ${val};`).join('\n');

const root: [string, string][] = [
  ...Object.entries(palette).map(([k, val]): [string, string] => [v(k), val]),
  ...Object.entries(tones).flatMap(([k, t]): [string, string][] => [
    [v(`tone-${k}`), t.face],
    [v(`tone-${k}-deep`), t.deep],
  ]),
  ...Object.entries(space).map(([k, val]): [string, string] => [v(`space-${k}`), val]),
  ...Object.entries(radius).map(([k, val]): [string, string] => [v(`radius-${k}`), val]),
  ...Object.entries(font).map(([k, val]): [string, string] => [v(`font-${k}`), val]),
  ...Object.entries(fontSize).map(([k, val]): [string, string] => [v(`text-${k}`), val]),
  ...Object.entries(motion).map(([k, val]): [string, string] => [v(`motion-${k}`), val]),
  ...Object.entries(depth).map(([k, val]): [string, string] => [v(`depth-${k}`), val]),
  ...Object.entries(size).map(([k, val]): [string, string] => [v(`size-${k}`), val]),
];

const themeBlock = (name: keyof typeof themes) =>
  lines(Object.entries(themes[name]).map(([k, val]): [string, string] => [v(k), val]), '    ');

const tokensCss = `${header}
@layer jaml.tokens {
  :root {
${lines(root, '    ')}
  }

  :root,
  [data-theme='dark'] {
    color-scheme: dark;
${themeBlock('dark')}
  }

  [data-theme='light'] {
    color-scheme: light;
${themeBlock('light')}
  }

  @media (prefers-reduced-motion: reduce) {
    :root {
      --j-motion-ease: 1ms linear;
      --j-motion-bounce: 0s;
    }
  }

  [data-motion='reduced'] {
    --j-motion-ease: 1ms linear;
    --j-motion-bounce: 0s;
  }
}
`;

const tw: [string, string][] = [
  ...Object.keys(palette).map((k): [string, string] => [`--color-j-${kebab(k)}`, `var(${v(k)})`]),
  ...Object.keys(tones).map((k): [string, string] => [`--color-j-tone-${k}`, `var(${v(`tone-${k}`)})`]),
  ...Object.keys(themes.dark)
    .filter((k) => k !== 'textShadow')
    .map((k): [string, string] => [`--color-j-${kebab(k)}`, `var(${v(k)})`]),
  ...Object.keys(space).map((k): [string, string] => [`--spacing-j-${k}`, `var(${v(`space-${k}`)})`]),
  ...Object.keys(radius).map((k): [string, string] => [`--radius-j-${k}`, `var(${v(`radius-${k}`)})`]),
  ...Object.keys(font).map((k): [string, string] => [`--font-${k}`, `var(${v(`font-${k}`)})`]),
  ...Object.keys(fontSize).map((k): [string, string] => [`--text-j-${k}`, `var(${v(`text-${k}`)})`]),
];

const tailwindCss = `${header}
/*
 * Tailwind v4 bridge. In your app's CSS:
 *   @import 'tailwindcss';
 *   @import 'jaml-ui/tailwind.css';
 * Utilities like bg-j-surface, text-j-gold, rounded-j-md and font-jimbo then
 * follow the same runtime theme as the components.
 */
@theme inline {
${lines(tw)}
}
`;

const out = {
  'src/styles/tokens.css': tokensCss,
  'src/styles/tailwind.css': tailwindCss,
};

const root_ = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
let stale = false;
for (const [rel, css] of Object.entries(out)) {
  const path = root_ + rel;
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {}
    if (current !== css) {
      console.error(`stale: ${rel} (run pnpm tokens)`);
      stale = true;
    }
  } else {
    writeFileSync(path, css);
    console.log(`wrote ${rel}`);
  }
}
if (stale) process.exit(1);
